"""User-level policy and provider settings.

policy.toml    limits a job spec can tighten but never loosen, plus rent-vs-buy inputs.
providers.toml which providers are configured and where their API keys live (op:// refs, never keys).

Both live in the gpu-ops config dir (see paths.py), outside every project repo.
Agents must not edit them (AGENTS.md says so; nothing technically stops a process running as you).
"""

from __future__ import annotations

import tomllib
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field, ValidationError

from .errors import ExitCode, GpuOpsError
from .paths import config_dir


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class PolicyLimits(_Strict):
    max_job_usd: float = Field(default=5.0, gt=0, description="Worst-case cost allowed for one run.")
    max_month_usd: float = Field(default=50.0, gt=0, description="Spend this calendar month + this run's worst case.")
    max_job_minutes: float = Field(default=360, gt=0)
    max_concurrent: int = Field(default=2, ge=1, description="gpu-ops instances alive at once, across providers.")
    allow_unarmed_deadman_minutes: float = Field(
        default=120, ge=0,
        description="Longest run allowed when the dead-man timer could not be armed on the instance.")


class PolicyProviders(_Strict):
    allowed: list[str] = Field(default_factory=lambda: ["runpod"])


class RentVsBuy(_Strict):
    card_price_usd: float = Field(default=0, ge=0, description="0 = not set yet.")
    warn_monthly_usd: float = Field(default=0, ge=0, description="0 = no warning.")


class Policy(_Strict):
    limits: PolicyLimits = Field(default_factory=PolicyLimits)
    providers: PolicyProviders = Field(default_factory=PolicyProviders)
    rent_vs_buy: RentVsBuy = Field(default_factory=RentVsBuy)


DEFAULT_POLICY_TOML = """\
# gpu-ops policy. Limits here can be tightened by a job spec but never loosened.
# Agents: do not edit this file. Ask the human.

[limits]
max_job_usd = 5.0               # worst-case cost of one run
max_month_usd = 50.0            # this month's spend + a run's worst case must stay under this
max_job_minutes = 360
max_concurrent = 2
allow_unarmed_deadman_minutes = 120   # longest run allowed if the on-instance dead-man timer can't be armed

[providers]
allowed = ["runpod"]

[rent_vs_buy]
card_price_usd = 0              # TODO(human): price of the card you'd buy instead (e.g. RTX PRO 6000 Max-Q)
warn_monthly_usd = 0            # TODO(human): warn when the trailing 3-month average passes this
"""

DEFAULT_PROVIDERS_TOML = """\
# gpu-ops provider settings. API keys are 1Password references, never the key itself.

[runpod]
api_key_ref = "op://Private/Runpod API Keys/credential"
"""


def _load_toml(path: Path) -> dict:
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as e:
        raise GpuOpsError(ExitCode.REFUSED, f"{path}: invalid TOML: {e}")


def policy_path() -> Path:
    return config_dir() / "policy.toml"


def providers_path() -> Path:
    return config_dir() / "providers.toml"


def load_policy() -> Policy:
    p = policy_path()
    if not p.exists():
        raise GpuOpsError(ExitCode.REFUSED, f"no policy file at {p}. A human must run `gpu-ops init` and review it.")
    try:
        return Policy.model_validate(_load_toml(p))
    except ValidationError as e:
        raise GpuOpsError(ExitCode.REFUSED, f"{p}: invalid policy: {e}")


def load_provider_settings() -> dict:
    p = providers_path()
    return _load_toml(p) if p.exists() else {}


def init_config(force: bool = False) -> list[Path]:
    """Write default policy.toml and providers.toml if missing. Returns the files written."""
    written = []
    for path, text in ((policy_path(), DEFAULT_POLICY_TOML), (providers_path(), DEFAULT_PROVIDERS_TOML)):
        if path.exists() and not force:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written
